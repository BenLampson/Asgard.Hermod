using System.Data.Common;

namespace Asgard.Hermod.PostgreSql;

/// <summary>读取字段、域约束和原始默认表达式；键类别表示成员身份，不推断单列唯一性。</summary>
internal static class PostgreSqlColumnMetadata
{
    internal const string Sql = "SELECT a.attname, format_type(a.atttypid,a.atttypmod), a.attnum, NOT (a.attnotnull OR t.typnotnull), " +
        "CASE WHEN EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conrelid=c.oid AND k.contype='p' AND a.attnum=ANY(k.conkey)) THEN 'PRI' " +
        "WHEN EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conrelid=c.oid AND k.contype='u' AND a.attnum=ANY(k.conkey)) THEN 'UNI' " +
        "WHEN EXISTS (SELECT 1 FROM pg_index i WHERE i.indrelid=c.oid AND i.indisvalid AND a.attnum=ANY(i.indkey)) THEN 'MUL' ELSE '' END, " +
        "CASE WHEN a.attgenerated='' THEN COALESCE(pg_get_expr(d.adbin,d.adrelid),t.typdefault) ELSE NULL END, " +
        "CASE a.attidentity WHEN 'a' THEN 'GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY' " +
        "ELSE CASE a.attgenerated WHEN 's' THEN 'STORED' WHEN 'v' THEN 'VIRTUAL' ELSE '' END END, COALESCE(col_description(c.oid,a.attnum),''), " +
        "CASE WHEN a.attgenerated<>'' THEN pg_get_expr(d.adbin,d.adrelid) ELSE '' END " +
        "FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace JOIN pg_type t ON t.oid=a.atttypid " +
        "LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum " +
        "WHERE n.nspname=@schema AND c.relname=@parent AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum";
    internal static DatabaseColumnDefinition Read(DbDataReader reader) => new(Convert.ToInt32(reader.GetValue(2), CultureInfo.InvariantCulture), reader.GetString(1), reader.IsDBNull(3) ? null : reader.GetBoolean(3),
        reader.IsDBNull(4) ? DatabaseColumnKeyKind.Unknown : reader.GetString(4) switch { "PRI" => DatabaseColumnKeyKind.Primary, "UNI" => DatabaseColumnKeyKind.Unique, "MUL" => DatabaseColumnKeyKind.Indexed, "" => DatabaseColumnKeyKind.None, _ => DatabaseColumnKeyKind.Unknown },
        reader.IsDBNull(5) ? null : reader.GetString(5), reader.IsDBNull(6) ? "" : reader.GetString(6), reader.IsDBNull(7) ? "" : reader.GetString(7))
    { GenerationExpression = reader.IsDBNull(8) ? "" : reader.GetString(8) };
}
